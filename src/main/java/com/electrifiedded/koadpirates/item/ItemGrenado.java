public class ItemGrenado extends Item {
    public ItemGrenado() { this.setMaxStackSize(16); }

    @Override
    public ActionResult<ItemStack> onItemRightClick(World world, EntityPlayer player, EnumHand hand) {
        ItemStack s = player.getHeldItem(hand);
        if (!player.capabilities.isCreativeMode) s.shrink(1);
        world.playSound(null, player.posX, player.posY, player.posZ, SoundEvents.ENTITY_ARROW_SHOOT, SoundCategory.PLAYERS, 0.5F, 0.4F / (itemRand.nextFloat() * 0.4F + 0.8F));
        if (!world.isRemote) world.spawnEntity(new EntityGrenado(world, player));
        return new ActionResult<>(EnumActionResult.SUCCESS, s);
    }
}
